"""
Nutrition Agentic AI - Core Agent Logic
Uses IBM Granite LLM via IBM watsonx.ai
Applies HAM (Helpful, Accurate, Mindful) tone with guardrails and ethics.
"""

import os
import re
from datetime import datetime
from ibm_watsonx_ai import APIClient, Credentials
from ibm_watsonx_ai.foundation_models import ModelInference
from ibm_watsonx_ai.metanames import GenTextParamsMetaNames as GenParams

# ── Guardrails: topics that must NEVER produce harmful advice ──────────────
HARMFUL_KEYWORDS = [
    "suicide", "self-harm", "overdose", "starve yourself",
    "laxative abuse", "diet pills", "extreme fasting", "crash diet"
]

MEDICAL_DISCLAIMER = """
---
> ⚕️ **Medical Disclaimer**
> This nutrition plan is generated by an AI system for **informational purposes only**.
> It is **not** a substitute for professional medical advice, diagnosis, or treatment.
> Always consult a qualified healthcare provider or registered dietitian before making
> significant changes to your diet, especially if you have a medical condition such as
> diabetes, hypertension, kidney disease, or any other chronic illness.
> The creators of this application bear no liability for decisions made based on this plan.
---
"""


def get_watsonx_model():
    """Initialise IBM Granite model via watsonx.ai credentials from env vars."""
    api_key  = os.environ.get("WATSONX_API_KEY", "")
    project_id = os.environ.get("WATSONX_PROJECT_ID", "")
    url      = os.environ.get("WATSONX_URL", "https://us-south.ml.cloud.ibm.com")

    if not api_key or not project_id:
        return None  # will fall back to rule-based generation

    try:
        credentials = Credentials(url=url, api_key=api_key)
        client = APIClient(credentials)
        model = ModelInference(
            model_id="ibm/granite-13b-instruct-v2",
            credentials=credentials,
            project_id=project_id,
            params={
                GenParams.MAX_NEW_TOKENS: 1024,
                GenParams.TEMPERATURE: 0.7,
                GenParams.TOP_P: 0.9,
                GenParams.REPETITION_PENALTY: 1.1,
            }
        )
        return model
    except Exception:
        return None


def apply_guardrails(text: str) -> str:
    """Block or sanitise any content that violates safety guardrails."""
    lower = text.lower()
    for kw in HARMFUL_KEYWORDS:
        if kw in lower:
            return (
                "⚠️ I'm unable to provide advice on that topic as it may be harmful. "
                "Please consult a qualified healthcare professional for guidance."
            )
    return text


