def generate_nutrition_plan(user: dict) -> str:
    """Main entry: try Granite LLM first, fallback to rule-based."""
    model = get_watsonx_model()
    if model:
        try:
            prompt   = build_nutrition_prompt(user)
            response = model.generate_text(prompt=prompt)
            result   = apply_guardrails(response)
            return result + MEDICAL_DISCLAIMER
        except Exception:
            pass
    return rule_based_nutrition_plan(user)


def answer_query(question: str, user_context: dict = None) -> str:
    """Answer a user nutrition question via Granite or a friendly fallback."""
    safe_q = apply_guardrails(question)
    if safe_q != question:
        return safe_q

    model = get_watsonx_model()
    if model:
        try:
            prompt   = build_qa_prompt(question, user_context)
            response = model.generate_text(prompt=prompt)
            return apply_guardrails(response)
        except Exception:
            pass

    # Rule-based Q&A fallback
    q_lower = question.lower()
    if "protein" in q_lower:
        return ("Great question! Protein is essential for muscle repair and immune function. "
                "Good sources include lentils, chickpeas, tofu (vegetarian) or chicken, eggs, fish (non-veg). "
                "Aim for 0.8–1.2 g per kg of body weight daily. 💪")
    if "diabetes" in q_lower or "sugar" in q_lower:
        return ("For diabetes management, focus on low-glycaemic foods: oats, legumes, leafy greens, whole grains. "
                "Avoid white rice, white bread, sugary beverages, and sweets. "
                "Always consult your endocrinologist for a tailored plan. 🩺")
    if "blood pressure" in q_lower or "hypertension" in q_lower:
        return ("For blood pressure control, follow a DASH-style diet: rich in fruits, vegetables, whole grains, "
                "and low-fat dairy. Reduce sodium to <2300 mg/day and avoid processed foods. 🫀")
    if "weight loss" in q_lower:
        return ("For sustainable weight loss, aim for a 300–500 kcal daily deficit through a balanced diet "
                "and regular exercise. Prioritise whole foods, fibre, and lean protein. Avoid crash diets. 🥦")
    if "vitamin" in q_lower or "mineral" in q_lower:
        return ("Vitamins and minerals are micronutrients vital for body functions. Eat a rainbow of vegetables "
                "and fruits to cover most micronutrient needs. Supplements should only be taken on medical advice. 🌈")
    if "water" in q_lower or "hydration" in q_lower:
        return ("Staying hydrated is crucial! Aim for 8–10 glasses (2–2.5 litres) daily. "
                "Water supports digestion, skin health, and energy levels. 💧")

    return ("That's a thoughtful question! For personalised advice, I recommend generating your full nutrition plan "
            "or consulting a registered dietitian. I'm here to help with general nutrition questions anytime! 😊")
